def test_store_set_get_round_trip(catalog: Catalog) -> None:
    sha = "a" * 64
    _register_content(catalog, sha)
    store = EmbeddingStore(catalog)
    vector = np.random.RandomState(1).uniform(-1, 1, size=(EMBEDDING_DIM,)).astype(np.float32)
    store.set(sha, "v1", vector)
    loaded = store.get(sha, "v1")
    assert loaded is not None
    assert np.allclose(vector, loaded.vector)
    assert loaded.dim == EMBEDDING_DIM
    assert loaded.model_version == "v1"
    assert loaded.sha256 == sha


def test_store_set_upsert_overwrites_in_place(catalog: Catalog) -> None:
    sha = "a" * 64
    _register_content(catalog, sha)
    store = EmbeddingStore(catalog)
    v1 = np.full((EMBEDDING_DIM,), 1.0, dtype=np.float32)
    v2 = np.full((EMBEDDING_DIM,), 2.0, dtype=np.float32)
    store.set(sha, "v1", v1)
    store.set(sha, "v1", v2)
    loaded = store.get(sha, "v1")
    assert loaded is not None
    assert np.array_equal(loaded.vector, v2)
    count = catalog.db.execute(
        "SELECT COUNT(*) FROM content_embeddings WHERE sha256 = ? AND model_version = ?",
        (sha, "v1"),
    ).fetchone()[0]
    assert count == 1


def test_store_get_absent_returns_none(catalog: Catalog) -> None:
    store = EmbeddingStore(catalog)
    assert store.get("b" * 64, "v1") is None


def test_get_matrix_returns_shas_and_matrix_ordered_by_sha(catalog: Catalog) -> None:
    store = EmbeddingStore(catalog)
    vectors = {
        "c" * 64: np.full((EMBEDDING_DIM,), 3.0, dtype=np.float32),
        "a" * 64: np.full((EMBEDDING_DIM,), 1.0, dtype=np.float32),
        "b" * 64: np.full((EMBEDDING_DIM,), 2.0, dtype=np.float32),
    }
    for sha, vec in vectors.items():
        _register_content(catalog, sha)
        store.set(sha, "v1", vec)
    shas, matrix = store.get_matrix("v1")
    assert shas == sorted(vectors)
    assert matrix.shape == (3, EMBEDDING_DIM)
    for i, sha in enumerate(shas):
        assert np.array_equal(matrix[i], vectors[sha])


def test_get_matrix_empty_version_returns_correctly_shaped_empty(catalog: Catalog) -> None:
    store = EmbeddingStore(catalog)
    shas, matrix = store.get_matrix("nonexistent-version")
    assert shas == []
    assert matrix.shape == (0, EMBEDDING_DIM)


