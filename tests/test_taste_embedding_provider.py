def test_capabilities_reports_dim_backend_deterministic_air_gapped(
    provider: OnnxEmbeddingProvider,
) -> None:
    caps = provider.capabilities()
    assert caps.dim == EMBEDDING_DIM == 512
    assert caps.backends == frozenset({ComputeBackend.CPU})
    assert caps.deterministic is True
    assert caps.air_gapped is True


def test_probe_model_absent_reports_ok_false_never_raises(tmp_path: Path) -> None:
    missing = OnnxEmbeddingProvider(model_path=tmp_path / "nonexistent.onnx")
    probe = missing.probe()
    assert probe.ok is False
    assert "not available" in (probe.message or "")


def test_probe_model_present_reports_ok_true(provider: OnnxEmbeddingProvider) -> None:
    probe = provider.probe()
    assert probe.ok is True


def test_probe_checksum_mismatch_reports_ok_false(tmp_path: Path) -> None:
    wrong_hash = "0" * 64
    provider = OnnxEmbeddingProvider(model_path=FIXTURE_MODEL, expected_sha256=wrong_hash)
    probe = provider.probe()
    assert probe.ok is False
    assert "checksum mismatch" in (probe.message or "")


def test_probe_checksum_match_reports_ok_true() -> None:
    correct_hash = sha256_hex(FIXTURE_MODEL.read_bytes())
    provider = OnnxEmbeddingProvider(model_path=FIXTURE_MODEL, expected_sha256=correct_hash)
    assert provider.probe().ok is True


