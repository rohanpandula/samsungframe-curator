def test_embed_same_session_bit_identical(provider: OnnxEmbeddingProvider) -> None:
    data = _image_bytes()
    v1 = provider.embed(data)
    v2 = provider.embed(data)
    assert v1.shape == (EMBEDDING_DIM,)
    assert v1.dtype == np.float32
    assert np.array_equal(v1, v2)


def test_embed_fresh_sessions_bit_identical() -> None:
    data = _image_bytes()
    v1 = OnnxEmbeddingProvider(
        model_path=FIXTURE_MODEL, model_version="test-fixture-1"
    ).embed(data)
    v2 = OnnxEmbeddingProvider(
        model_path=FIXTURE_MODEL, model_version="test-fixture-1"
    ).embed(data)
    assert np.array_equal(v1, v2)


